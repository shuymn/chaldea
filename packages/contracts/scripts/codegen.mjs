// Compiles every schema under schema/ into standalone validators, so the page runs no
// `eval` (docs/design/w1-pwa.md §2.5), and writes them to src/validate/, which is
// generated and not committed. `typecheck` and `test` run this first.
//
// Ajv 2020 in strict mode, with every format the schemas use registered explicitly:
// `uuid` from ajv-formats (a regular expression, inlined), and the integer widths
// schemars writes as formats, as Rust decodes them (each schema also bounds them with
// `minimum`/`maximum`). Strict mode fails the compile on a format nobody registered, so
// a new one cannot pass unchecked.
//
// The output is plain ES modules: Ajv's `require` of its runtime and of the format
// functions is rewritten to imports of the generated formats.js, and any other `require`
// fails the script.

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import { _ } from "ajv/dist/compile/codegen/index.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = join(root, "schema");
const outDir = join(root, "src", "validate");
const HEADER = "// Generated by scripts/codegen.mjs from schema/. Do not edit.\n";

// [min, max] of each width, the 64-bit ones stopping at Number.MAX_SAFE_INTEGER
// (crates/core/tests/contracts_export.rs `bound_integers`).
const widths = {
  uint8: ["0", "0xff"],
  uint16: ["0", "0xffff"],
  uint32: ["0", "0xffffffff"],
  uint64: ["0", "Number.MAX_SAFE_INTEGER"],
  int32: ["-0x80000000", "0x7fffffff"],
  int64: ["-Number.MAX_SAFE_INTEGER", "Number.MAX_SAFE_INTEGER"],
};

const formatsJs = `${HEADER}
/** The integer formats, as Ajv format definitions: an integer within the width. */
export const formats = {
${Object.entries(widths)
  .map(
    ([n, [min, max]]) =>
      `  ${n}: { type: "number", validate: (n) => Number.isInteger(n) && n >= ${min} && n <= ${max} },`,
  )
  .join("\n")}
};

/** The length of \`s\` in code points, as JSON Schema counts it (Ajv's ucs2length). */
export function ucs2length(s) {
  let length = 0;
  for (const _c of s) length++;
  return length;
}
`;

const formatsDts = `${HEADER}
export declare const formats: Record<string, { type: "number"; validate: (n: number) => boolean }>;
export declare function ucs2length(s: string): number;
`;

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "formats.js"), formatsJs);
writeFileSync(join(outDir, "formats.d.ts"), formatsDts);
const { formats } = await import(pathToFileURL(join(outDir, "formats.js")).href);

const ajv = new Ajv2020({ strict: true, code: { source: true, esm: true, lines: true } });
addFormats(ajv, { formats: ["uuid"] });
for (const [name, def] of Object.entries(formats)) {
  ajv.addFormat(name, def);
}
// Function formats resolve through `formats.<name>` (imported below).
ajv.opts.code.formats = _`formats`;

const names = readdirSync(schemaDir)
  .filter((f) => f.endsWith(".schema.json"))
  .map((f) => f.slice(0, -".schema.json".length))
  .sort();
for (const name of names) {
  const schema = JSON.parse(readFileSync(join(schemaDir, `${name}.schema.json`), "utf8"));
  ajv.addSchema({ ...schema, $id: name });
}
let code = standaloneCode(ajv, Object.fromEntries(names.map((n) => [n, n])));
code = code.replaceAll('require("ajv/dist/runtime/ucs2length").default', "ucs2length");
const left = code.match(/require\([^)]*\)/);
if (left) {
  throw new Error(`the generated validators still call ${left[0]}`);
}
code = code.replace(
  '"use strict";',
  `"use strict";\n${HEADER}import { formats, ucs2length } from "./formats.js";`,
);
writeFileSync(join(outDir, "validators.js"), code);

// Each validator, typed by the generated type of the same name.
const generated = join(root, "src", "generated");
const dts = [HEADER, 'import type { ErrorObject } from "ajv";'];
dts.push(
  "export type Validator<T> = ((data: unknown) => data is T) & { errors?: ErrorObject[] | null };",
);
for (const n of names) {
  const type = existsSync(join(generated, `${n}.ts`)) ? `import("../generated/${n}").${n}` : "unknown";
  dts.push(`export declare const ${n}: Validator<${type}>;`);
}
writeFileSync(join(outDir, "validators.d.ts"), `${dts.join("\n")}\n`);

// The kinds `TypedEvent` decodes: the `kind` constants of its `oneOf`.
const typed = JSON.parse(readFileSync(join(schemaDir, "TypedEvent.schema.json"), "utf8"));
const kinds = typed.oneOf.map((v) => v.properties.kind.const);
if (kinds.some((k) => typeof k !== "string") || kinds.length === 0) {
  throw new Error("TypedEvent's oneOf does not name each kind with a constant");
}
writeFileSync(
  join(outDir, "kinds.js"),
  `${HEADER}export const typedKinds = new Set(${JSON.stringify(kinds)});\n`,
);
writeFileSync(
  join(outDir, "kinds.d.ts"),
  `${HEADER}export declare const typedKinds: ReadonlySet<string>;\n`,
);
