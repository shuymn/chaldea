/// A closed enum read openly: a known value, or the string of one this reader does not
/// know, kept as received. Used where an unknown value must not fail its container (the
/// envelope's `source`, the thread list of a snapshot): a newer daemon may name an agent
/// or source kind that an older reader has never seen (§2.1 open envelope).
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Open<T> {
    Known(T),
    Unknown(String),
}

impl<T> From<T> for Open<T> {
    fn from(t: T) -> Self {
        Open::Known(t)
    }
}

impl<T: Serialize> Serialize for Open<T> {
    fn serialize<S: Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        match self {
            Open::Known(t) => t.serialize(s),
            Open::Unknown(v) => s.serialize_str(v),
        }
    }
}

impl<'de, T: serde::de::DeserializeOwned> Deserialize<'de> for Open<T> {
    fn deserialize<D: Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        let s = String::deserialize(d)?;
        let de = serde::de::value::StrDeserializer::<serde::de::value::Error>::new(&s);
        Ok(T::deserialize(de).map_or(Open::Unknown(s), Open::Known))
    }
}

/// On the wire an open value is a string; readers match the known values and keep the rest.
impl<T: TS> TS for Open<T> {
    type WithoutGenerics = Self;
    type OptionInnerType = Self;

    fn name(cfg: &ts_rs::Config) -> String {
        format!("{} | string", T::name(cfg))
    }

    fn inline(cfg: &ts_rs::Config) -> String {
        format!("{} | string", T::inline(cfg))
    }

    fn visit_dependencies(v: &mut impl ts_rs::TypeVisitor)
    where
        Self: 'static,
    {
        T::visit_dependencies(v);
    }

    fn visit_generics(v: &mut impl ts_rs::TypeVisitor)
    where
        Self: 'static,
    {
        T::visit_generics(v);
        v.visit::<T>();
    }
}

impl<T: JsonSchema> JsonSchema for Open<T> {
    fn schema_name() -> Cow<'static, str> {
        format!("Open{}", T::schema_name()).into()
    }

    fn json_schema(g: &mut SchemaGenerator) -> Schema {
        let known = g.subschema_for::<T>();
        json_schema!({
            "description": "A known value, or a string this reader does not know.",
            "anyOf": [known, { "type": "string" }]
        })
    }
}

/// Error for a malformed `StreamId` or `Actor` string.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ParseIdError(pub &'static str);

impl fmt::Display for ParseIdError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.0)
    }
}

impl std::error::Error for ParseIdError {}

/// Parses the canonical hyphenated lowercase form only, so that one id has one spelling
/// on the wire (stream ids are compared as strings by clients and the relay).
fn parse_canonical_uuid(s: &str) -> Option<Uuid> {
    let u = Uuid::try_parse(s).ok()?;
    (u.hyphenated().encode_lower(&mut Uuid::encode_buffer()) == s).then_some(u)
}

const UUID_PATTERN: &str = "[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}";

/// `host` or `thread:<uuid>` (§2.1 "Streams").
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, TS)]
#[ts(type = "string")]
pub enum StreamId {
    Host,
    Thread(ThreadId),
}

impl fmt::Display for StreamId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            StreamId::Host => f.write_str("host"),
            StreamId::Thread(t) => write!(f, "thread:{t}"),
        }
    }
}

impl FromStr for StreamId {
    type Err = ParseIdError;
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        if s == "host" {
            return Ok(StreamId::Host);
        }
        s.strip_prefix("thread:")
            .and_then(parse_canonical_uuid)
            .map(|u| StreamId::Thread(ThreadId(u)))
            .ok_or(ParseIdError(
                "stream id must be `host` or `thread:<lowercase hyphenated uuid>`",
            ))
    }
}

/// Who caused a change: `human`, `thread:<uuid>`, or `daemon`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, TS)]
#[ts(type = "string")]
pub enum Actor {
    /// The owner, through the CLI or the PWA.
    Human,
    /// An agent thread, through its agent token.
    Thread(ThreadId),
    /// The daemon itself (restart recovery, timers, hook ingest).
    Daemon,
}

impl fmt::Display for Actor {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Actor::Human => f.write_str("human"),
            Actor::Thread(t) => write!(f, "thread:{t}"),
            Actor::Daemon => f.write_str("daemon"),
        }
    }
}

impl FromStr for Actor {
    type Err = ParseIdError;
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s {
            "human" => Ok(Actor::Human),
            "daemon" => Ok(Actor::Daemon),
            _ => s
                .strip_prefix("thread:")
                .and_then(parse_canonical_uuid)
                .map(|u| Actor::Thread(ThreadId(u)))
                .ok_or(ParseIdError(
                    "actor must be `human`, `daemon`, or `thread:<lowercase hyphenated uuid>`",
                )),
        }
    }
}

macro_rules! string_form {
    ($name:ident, $schema_name:literal, $pattern:expr) => {
        impl Serialize for $name {
            fn serialize<S: Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
                s.collect_str(self)
            }
        }

        impl<'de> Deserialize<'de> for $name {
            fn deserialize<D: Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
                let s = String::deserialize(d)?;
                s.parse().map_err(serde::de::Error::custom)
            }
        }

        impl JsonSchema for $name {
            fn schema_name() -> Cow<'static, str> {
                $schema_name.into()
            }
            fn json_schema(_: &mut SchemaGenerator) -> Schema {
                json_schema!({ "type": "string", "pattern": $pattern })
            }
        }
    };
}

string_form!(
    StreamId,
    "StreamId",
    format!("^(host|thread:{UUID_PATTERN})$")
);
string_form!(
    Actor,
    "Actor",
    format!("^(human|daemon|thread:{UUID_PATTERN})$")
);

#[cfg(test)]
mod tests {
    use super::stamp_millis;

    /// The stamp format and its boundaries.
    #[test]
    fn timestamp() {
        assert_eq!(stamp_millis("1970-01-01T00:00:00.000Z"), Some(0));
        assert_eq!(stamp_millis("1970-01-01T00:00:01.001Z"), Some(1001));
        assert_eq!(
            stamp_millis("2000-03-01T00:00:00.000Z"),
            Some(951_868_800_000)
        );
        assert_eq!(
            stamp_millis("2024-02-29T23:59:59.999Z"),
            Some(1_709_251_199_999)
        );
        assert_eq!(
            stamp_millis("2026-11-22T00:00:30.000Z").unwrap()
                - stamp_millis("2026-11-22T00:00:00.000Z").unwrap(),
            30_000
        );
        // Across a year boundary.
        assert_eq!(
            stamp_millis("2027-01-01T00:00:00.000Z").unwrap()
                - stamp_millis("2026-12-31T23:59:59.999Z").unwrap(),
            1
        );
        for bad in [
            "",
            "2026-11-22T00:00:00Z",
            "2026-11-22T00:00:00.000",
            "2026-11-22 00:00:00.000Z",
            "2026-13-01T00:00:00.000Z",
            "2026-02-29T00:00:00.000Z",
            "2026-11-22T24:00:00.000Z",
            "2026-11-22T00:60:00.000Z",
            "2026-11-22T00:00:60.000Z",
            "2026-11-22T00:00:00.+00Z",
            "+026-11-22T00:00:00.000Z",
        ] {
            assert_eq!(stamp_millis(bad), None, "{bad}");
        }
    }
}
